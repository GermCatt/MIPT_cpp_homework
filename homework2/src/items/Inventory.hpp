#pragma once

#include <compare>
#include <iosfwd>
#include <string>

class Item {
 private:
  // Всё-таки поля переехали сюда. Они есть у всех предметов, так что хранить
  // их отдельно у транспорта и у шлемов было как-то обидно.
  std::string id_;
  std::string name_;

 protected:
  Item(const std::string& id, const std::string& name);

 public:
  /*
    Тут костыль. По условию Describe должен быть чисто
    виртуальным, но собирать одну и ту же строку у разных детей мне лень.
    Оказывается, = 0 не запрещает написать тело функции отдельно, за классом.
    Функция всё ещё чисто виртуальная, а дети переопределяют её и явно зовут
    Item::Describe(). И условие соблюдено, и копипасты меньше. Красота.
    С GetId и GetName тот же фокус: они тоже остаются чисто виртуальными,
    а поля остаются private. Лезть в них детям своими руками незачем.
    А всё потому, что в условии написали, что эти методы должны быть чисто
    виртуальными
  */
  virtual std::string Describe() const = 0;

  // Функция для реализации творческой части
  virtual std::string Details() const = 0;

  virtual const std::string& GetId() const = 0;
  virtual const std::string& GetName() const = 0;

  // Функция для составления списка трансопрта, пригодного для новичков. Чтобы
  // при вызове функцииц печати транспорта пригодного для новичков не делать
  // проверку типов, для любого объекта базовое значение функции - false. В
  // классе транспорта эта функция будет переопределена
  virtual bool IncludeInNoviceList() const;

  // Функция для техосмотра. Там, где он нужен, она переопределна на true. Таким
  // образом, при добавлении в парк мы не проверяем типы, а просто вызываем
  // функцию, которая есть у любого наследника item
  virtual bool RequiresInspection() const;

  // Функция для реализации творческой части
  virtual std::string TypeName() const = 0;

  virtual ~Item() = default;

  /*
    Перегружаю оператор сравнения. Вообще от меня явно требуют перегрузить
    оператор <, но это как-то не круто. Мало ли, понадобится. А так, эта штука
    есть-пить не просит, почему нет.
    (Я просто хвастаюсь что знаю модные методы 20-го стандарта)
  */
  auto operator<=>(const Item& other) const {
    return GetId() <=> other.GetId();
  }
};

std::ostream& operator<<(std::ostream& os, const Item& item);
